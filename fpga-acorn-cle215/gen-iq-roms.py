# Generates iq_gen_roms.v: the chirp and sin/cos ROMs used by iq_gen.v.
#
# The chirp must match chirp() in radar-bench/radar-bench.cu, which builds the
# matched filter: an LFM pulse of CHIRP_LEN samples sweeping 80% of the
# sampling bandwidth, phase = pi * 0.8 * (n - L/2)^2 / L.

import math

CHIRP_LEN = 512
CHIRP_AMP = 32000	# leave headroom below full scale
BW = 0.8
SINCOS_LEN = 1024
SINCOS_AMP = 32767


def rnd(x):
    return int(math.floor(x + 0.5))


def s16(v):
    return v & 0xffff


out = []
out.append("// Generated by gen-iq-roms.py; do not edit.")
out.append("")
out.append("// LFM chirp, %d complex samples, 4 per 128-bit word; each sample is" % CHIRP_LEN)
out.append("// {Q[15:0], I[15:0]}, with sample 4w+j in bits [32j+31:32j] of word w.")
out.append("module iq_chirp_rom(")
out.append("    input clk,")
out.append("    input [6:0] addr,")
out.append("    output reg [127:0] data")
out.append(");")
out.append("    always @(posedge clk)")
out.append("        case (addr)")
for w in range(CHIRP_LEN // 4):
    word = 0
    for j in range(4):
        n = 4 * w + j
        t = n - CHIRP_LEN / 2.0
        ph = math.pi * BW * t * t / CHIRP_LEN
        i = rnd(CHIRP_AMP * math.cos(ph))
        q = rnd(CHIRP_AMP * math.sin(ph))
        word |= ((s16(q) << 16) | s16(i)) << (32 * j)
    out.append("        7'd%d: data <= 128'h%032x;" % (w, word))
out.append("        default: data <= 128'h0;")
out.append("        endcase")
out.append("endmodule")
out.append("")
out.append("// {sin, cos} of 2*pi*addr/%d, Q15" % SINCOS_LEN)
out.append("module iq_sincos_rom(")
out.append("    input clk,")
out.append("    input [9:0] addr,")
out.append("    output reg [31:0] data")
out.append(");")
out.append("    always @(posedge clk)")
out.append("        case (addr)")
for a in range(SINCOS_LEN):
    ang = 2 * math.pi * a / SINCOS_LEN
    c = rnd(SINCOS_AMP * math.cos(ang))
    s = rnd(SINCOS_AMP * math.sin(ang))
    out.append("        10'd%d: data <= 32'h%08x;" % (a, (s16(s) << 16) | s16(c)))
out.append("        endcase")
out.append("endmodule")

with open("iq_gen_roms.v", "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print("wrote iq_gen_roms.v")
